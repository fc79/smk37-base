"""Write firmware/gen/pad_curves.h: Drumtonic's pad sensitivity, 5 curves from the velocity as read (1..127, straight
from a hit's start to a full hit, hal/smk_input.h) to the velocity played.

  level 1: as read; 2..5: 1 + 126 * ln(1 + k x) / ln(1 + k), x = (v - 1) / 126, k = 1.5, 4, 9, 20: a light hit plays
  louder, the middle gets a wide, gentle slope, only the hardest hit reaches 127 (a unit's pads, 2026-10-28: light hits
  too quiet, hard ones all at 127, medium ones hard to play with a straight line)

    python3 tools/gen_pad_curves.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'firmware' / 'gen' / 'pad_curves.h'
K = [0, 1.5, 4, 9, 20]


def curve(k):
    out = [0]
    for v in range(1, 128):
        x = (v - 1) / 126
        out.append(round(1 + 126 * (x if k == 0 else math.log(1 + k * x) / math.log(1 + k))))
    return out


rows = ',\n'.join('    {' + ', '.join(str(v) for v in curve(k)) + '}' for k in K)
OUT.write_text(f"""/* Generated by tools/gen_pad_curves.py: do not edit. */
#pragma once
#include <stdint.h>

#define PAD_NCURVE {len(K)}u
static const uint8_t PAD_CURVE[{len(K)}][128] = {{
{rows}
}};
""")
print(OUT)
